// Counts Standard-layout solutions for all 366 dates and writes standard_day_solutions.dart.
// Run: fvm flutter test tool/day_tiers/count_day_solutions_test.dart
// ignore_for_file: avoid_print

import 'dart:io';

import 'package:caesar_puzzle/application/puzzle_config_json.dart';
import 'package:caesar_puzzle/core/models/piece_type.dart';
import 'package:caesar_puzzle/core/models/position.dart';
import 'package:caesar_puzzle/domain/algorithms/dancing_links/models/solver_piece.dart';
import 'package:caesar_puzzle/domain/algorithms/exact_cover/caesar_puzzle_exact_cover_solver.dart';
import 'package:caesar_puzzle/domain/entities/puzzle_grid_entity.dart';
import 'package:caesar_puzzle/presentation/models/puzzle_piece_ui.dart';
import 'package:caesar_puzzle/presentation/utils/board_layout_cells.dart';
import 'package:caesar_puzzle/presentation/utils/piece_type_extension.dart';
import 'package:caesar_puzzle/presentation/utils/puzzle_piece_extension.dart';
import 'package:flutter_test/flutter_test.dart';

const _unit = 10.0;
const _grid = PuzzleGridEntity(cellSize: _unit, rows: 7, columns: 7, origin: Position.zero());

void main() {
  test('count Standard solutions for every calendar date', () {
    final pieces = [
      SolverPiece(
        id: 'blocked',
        cells: blockedCellsOf(PuzzleConfigJson.standardPlacements),
        isForbidden: true,
        isImmovable: true,
      ),
      for (final type in PieceType.values.where((final t) => !t.isConfigType))
        SolverPiece(
          id: type.idForType,
          cells: PuzzlePieceUI.fromType(
            type,
            Offset.zero,
            const Offset(_unit / 2, _unit / 2),
            _unit,
          ).relativeCells(_unit),
          isForbidden: false,
          isImmovable: false,
        ),
    ];

    final counts = <(int, int), int>{};
    for (var date = DateTime.utc(2024); date.year == 2024; date = date.add(const Duration(days: 1))) {
      final solver = CaesarPuzzleExactCoverSolver(grid: _grid, pieces: pieces, date: date);
      counts[(date.month, date.day)] = solver.solve().solutions.length;
    }

    expect(counts.length, 366);
    expect(counts[(10, 8)], 50);

    File('lib/application/leaderboard/standard_day_solutions.dart').writeAsStringSync(_dartTable(counts));

    final sorted = counts.values.toList()..sort();
    int percentile(final int p) => sorted[((sorted.length - 1) * p / 100).round()];
    print(
      'min ${sorted.first}, max ${sorted.last}, '
      'mean ${(sorted.reduce((final a, final b) => a + b) / sorted.length).toStringAsFixed(1)}',
    );
    const marks = [10, 20, 25, 33, 40, 50, 60, 67, 75, 80, 90];
    print('percentiles: ${[for (final p in marks) 'p$p=${percentile(p)}'].join(', ')}');
    final hardest = counts.entries.toList()..sort((final a, final b) => a.value.compareTo(b.value));
    print('fewest: ${hardest.take(10).map((final e) => '${e.key.$1}/${e.key.$2}=${e.value}').join(', ')}');
    print('most: ${hardest.reversed.take(10).map((final e) => '${e.key.$1}/${e.key.$2}=${e.value}').join(', ')}');
  }, timeout: const Timeout(Duration(minutes: 20)));
}

String _dartTable(final Map<(int, int), int> counts) {
  final values = [
    for (var date = DateTime.utc(2024); date.year == 2024; date = date.add(const Duration(days: 1)))
      counts[(date.month, date.day)]!,
  ];
  final out = StringBuffer()
    ..writeln('// Generated by tool/day_tiers/count_day_solutions_test.dart. Do not edit.')
    ..writeln()
    ..writeln('/// Standard-layout solution counts by day of a leap year (Jan 1 = 0).')
    ..writeln('// dart format off')
    ..writeln('const List<int> standardDaySolutions = [');
  for (var i = 0; i < values.length; i += 16) {
    out.writeln('  ${values.skip(i).take(16).join(', ')},');
  }
  out
    ..writeln('];')
    ..writeln('// dart format on');
  return out.toString();
}
